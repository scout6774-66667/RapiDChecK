# ─── 2. PREDICTION ITEM SCORING TESTS (Requirement 1 & 10) ────────────────────

def test_every_predicted_item_receives_risk_score():
    """
    Verify that every item generated by DiseasePredictor has:
    - risk_score between 0 and 100
    - valid risk_level (LOW, MODERATE, HIGH, CRITICAL)
    - item_id and required_specialty
    """
    result = disease_predictor.predict_disease(["fever", "cough", "fatigue"])
    predictions = result.get("predictions", [])
    assert len(predictions) > 0

    for item in predictions:
        assert "risk_score" in item
        assert "risk_level" in item
        assert "item_id" in item
        assert "required_specialty" in item
        
        # Verify score is in valid [0, 100] range
        assert 0.0 <= item["risk_score"] <= 100.0
        assert item["risk_level"] in ["LOW", "MODERATE", "HIGH", "CRITICAL"]
        assert len(item["item_id"]) > 0
        assert len(item["required_specialty"]) > 0


def test_item_risk_deterministic_and_condition_aware():
    """
    Verify that calculate_item_risk scores acute conditions higher than mild ones.
    """
    # Emergency condition vs benign condition
    cardiac_risk = calculate_item_risk(0.8, "angina", ["chest pain"])
    skin_risk = calculate_item_risk(0.8, "acne", [])

    assert cardiac_risk["risk_score"] > skin_risk["risk_score"]
    assert cardiac_risk["risk_level"] in ["HIGH", "CRITICAL"]
    assert skin_risk["risk_level"] == "LOW"


