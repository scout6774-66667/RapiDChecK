# ─── 4. CAPABILITY-AWARE HOSPITAL RECOMMENDATION TESTS (Requirements 5 & 6) ───

def test_hospital_recommendation_critical_prioritizes_capability_over_distance():
    """
    CRITICAL REQUIREMENT TEST:
    For a Critical case (e.g. angina, risk_score=85):
    - Top hospital must have 24/7 Emergency and ICU capability
    - Recommendation priority must be CRITICAL
    - Must NOT simply pick the closest facility (e.g. Sundarpur PHC is 1.1 km away
      but has no ICU/Emergency, so District Trauma Hospital at 4.8 km must rank higher).
    """
    recs = recommend_hospitals(
        condition="angina",
        risk_score=85.0,
        user_lat=22.723,
        user_lng=88.483,
        max_results=5
    )
    assert len(recs) > 0
    top_hospital = recs[0]

    # Top recommendation MUST have 24/7 Emergency and ICU for Critical cardiac case
    assert top_hospital["is_emergency_24x7"] is True
    assert top_hospital["icu_beds_available"] > 0
    assert top_hospital["recommendation_priority"] == "CRITICAL"
    assert "Emergency Priority Match" in top_hospital["reason"]
    assert top_hospital["travel_time_min"] > 0
    assert len(top_hospital["capability_match"]) > 0


def test_hospital_recommendation_routine_moderate_case():
    """
    For a moderate case (risk_score=45), routine community facilities are valid.
    """
    recs = recommend_hospitals(
        condition="anemia",
        risk_score=45.0,
        user_lat=22.723,
        user_lng=88.483,
        max_results=5
    )
    assert len(recs) > 0
    # No emergency panic priority
    assert any(h["recommendation_priority"] in ["HIGH", "STANDARD"] for h in recs)


